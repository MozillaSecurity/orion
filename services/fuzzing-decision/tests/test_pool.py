def test_task_image(mocker):
    """Task image references become task dependencies in generated fuzzing tasks."""
    conf = FuzzingPoolConfig(
        apply_to=[],
        artifacts={
            "/some-file.txt": {
                "type": "file",
                "url": "project/fuzzing/private/file.txt",
            },
            "/var/log/": {
                "type": "directory",
                "url": "project/fuzzing/private/var-log",
            },
        },
        base_dir=Path.cwd(),
        cloud="gcp",
        command=["run-fuzzing.sh"],
        container={
            "taskId": "task-image-abc",
            "type": "task-image",
            "path": "public/msys2.tar.bz2",
        },
        cpu="x64",
        cycle_time=parse_time("1h"),
        demand=False,
        disk_size=10,
        env={},
        imageset="anything",
        machine_types=["a2"],
        max_run_time=parse_time("30s"),
        max_tasks=0,
        name="Amazing fuzzing pool",
        nested_virtualization=False,
        parents=[],
        performance_monitoring_unit=False,
        platform="linux",
        pool_id="test",
        preprocess=None,
        routes=["notify.email.test@example.com"],
        run_as_admin=False,
        schedule_start=None,
        scopes=[],
        tasks=2,
        worker="docker",
    )

    task_ids, tasks = zip(*build_tasks(conf, "someTaskId"))

    # Check we have 2 valid generated task ids
    assert len(task_ids) == 2
    assert all(map(slugid.decode, task_ids))

    # Check we have 2 valid task definitions
    assert len(tasks) == 2

    def _get_date(value: str):
        assert isinstance(value, str)
        return datetime.strptime(value, "%Y-%m-%dT%H:%M:%S.%fZ")

    for i, task in enumerate(tasks):
        created = _get_date(task.pop("created"))
        deadline = _get_date(task.pop("deadline"))
